package ai

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"strings"
	"time"

	"bugcode-shield/internal/auth"
	"bugcode-shield/internal/finding"
	"bugcode-shield/internal/httputil"
	"bugcode-shield/internal/settings"

	"github.com/go-chi/chi/v5"
)

type Service struct {
	findings *finding.Service
	settings *settings.Service
	envKey   string
	envBase  string
	envModel string
}

func New(findings *finding.Service, creds *settings.Service, apiKey, baseURL, model string) *Service {
	if baseURL == "" {
		baseURL = "https://api.openai.com/v1"
	}
	if model == "" {
		model = "gpt-4o-mini"
	}
	return &Service{findings: findings, settings: creds, envKey: apiKey, envBase: strings.TrimRight(baseURL, "/"), envModel: model}
}

func (s *Service) Explain(w http.ResponseWriter, r *http.Request) {
	userID := auth.UserID(r.Context())
	apiKey, baseURL, model, err := s.resolve(r.Context(), userID)
	if err != nil {
		httputil.Error(w, http.StatusInternalServerError, "internal", "Internal server error")
		return
	}
	if strings.TrimSpace(apiKey) == "" {
		httputil.Error(w, http.StatusServiceUnavailable, "ai_disabled", "Add an OpenAI API key in Settings to use Ask AI. Recommendations are never applied automatically.")
		return
	}
	findingID := chi.URLParam(r, "findingID")
	f, err := s.findings.Get(r.Context(), userID, findingID)
	if err != nil {
		httputil.WriteAppError(w, err)
		return
	}
	text, err := s.complete(r.Context(), apiKey, baseURL, model, f)
	if err != nil {
		httputil.Error(w, http.StatusBadGateway, "ai_error", "The AI provider could not explain this finding")
		return
	}
	httputil.JSON(w, http.StatusOK, map[string]any{
		"finding_id":  f.ID,
		"source":      "ai",
		"disclaimer":  "This explanation is generated by an AI model and is not a verified scanner finding. BugCode Shield will not modify your source code unless you apply a change yourself.",
		"explanation": text,
	})
}

func (s *Service) resolve(ctx context.Context, userID string) (key, baseURL, model string, err error) {
	key, baseURL, model = strings.TrimSpace(s.envKey), s.envBase, s.envModel
	if s.settings == nil {
		return key, baseURL, model, nil
	}
	userKey, userBase, userModel, err := s.settings.OpenAI(ctx, userID)
	if err != nil {
		return "", "", "", err
	}
	if strings.TrimSpace(userKey) != "" {
		key = strings.TrimSpace(userKey)
	}
	if strings.TrimSpace(userBase) != "" {
		baseURL = strings.TrimRight(strings.TrimSpace(userBase), "/")
	}
	if strings.TrimSpace(userModel) != "" {
		model = strings.TrimSpace(userModel)
	}
	if baseURL == "" {
		baseURL = "https://api.openai.com/v1"
	}
	if model == "" {
		model = "gpt-4o-mini"
	}
	return key, baseURL, model, nil
}

func (s *Service) complete(ctx context.Context, apiKey, baseURL, model string, f finding.Finding) (string, error) {
	prompt := fmt.Sprintf(`You are a secure-coding assistant. Explain this scanner finding in plain language.
Do not claim you verified exploitation. Separate facts from speculation.
Cover: what the issue is, a realistic impact scenario, a secure implementation approach, why it might be a false positive, and relative priority.

Scanner: %s
Rule: %s
Severity: %s
Title: %s
Description: %s
File: %v
Lines: %v-%v
Snippet:
%s
`, f.Scanner, f.RuleID, f.Severity, f.Title, f.Description, f.FilePath, f.StartLine, f.EndLine, deref(f.Snippet))

	body, _ := json.Marshal(map[string]any{
		"model": model,
		"messages": []map[string]string{
			{"role": "system", "content": "You help developers understand security scanner output. You never provide exploit payloads or attack instructions."},
			{"role": "user", "content": prompt},
		},
		"temperature": 0.2,
	})
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, baseURL+"/chat/completions", bytes.NewReader(body))
	if err != nil {
		return "", err
	}
	req.Header.Set("Authorization", "Bearer "+apiKey)
	req.Header.Set("Content-Type", "application/json")
	client := &http.Client{Timeout: 45 * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	raw, _ := io.ReadAll(resp.Body)
	if resp.StatusCode >= 300 {
		return "", fmt.Errorf("ai provider status %d", resp.StatusCode)
	}
	var parsed struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}
	if err := json.Unmarshal(raw, &parsed); err != nil {
		return "", err
	}
	if len(parsed.Choices) == 0 {
		return "", fmt.Errorf("empty ai response")
	}
	return parsed.Choices[0].Message.Content, nil
}

func deref(v *string) string {
	if v == nil {
		return ""
	}
	return *v
}
